int font_init(SDL_Renderer *renderer)
{
    if (!renderer) return -1;

    log_msg("font_init: creating SDL2 atlas texture");

    /* Build an RGBA atlas: white pixels on transparent background.
     * SDL_SetTextureColorMod will tint to any desired colour at draw time. */
    SDL_Surface *surf = SDL_CreateRGBSurfaceWithFormat(
        0, ATLAS_W, ATLAS_H, 32, SDL_PIXELFORMAT_RGBA8888);
    if (!surf) return -1;

    SDL_FillRect(surf, NULL, 0x00000000);  /* transparent */

    Uint32 *pixels = (Uint32 *)surf->pixels;
    int pitch32 = surf->pitch / 4;

    for (int ch = 0; ch < NUM_CHARS; ch++) {
        int col = ch % ATLAS_COLS;
        int row = ch / ATLAS_COLS;
        const unsigned char *glyph = &font_data[ch * CHAR_H];

        for (int py = 0; py < CHAR_H; py++) {
            for (int px = 0; px < CHAR_W; px++) {
                if ((glyph[py] >> (7 - px)) & 1) {
                    int tx = col * CHAR_W + px;
                    int ty = row * CHAR_H + py;
                    pixels[ty * pitch32 + tx] = 0xFFFFFFFF;  /* RGBA: white opaque */
                }
            }
        }
    }

    g_atlas = SDL_CreateTextureFromSurface(renderer, surf);
    SDL_FreeSurface(surf);

    if (!g_atlas) return -1;
    SDL_SetTextureBlendMode(g_atlas, SDL_BLENDMODE_BLEND);

    log_msg("font_init: atlas texture created");
    return 0;
}

void font_shutdown(void)
{
    if (g_atlas) {
        SDL_DestroyTexture(g_atlas);
        g_atlas = NULL;
    }
}

void font_draw_string(SDL_Renderer *renderer, const char *text,
                      int x, int y, int scale,
                      Uint8 r, Uint8 g, Uint8 b)
{
    if (!renderer || !text || !g_atlas) return;

    SDL_SetTextureColorMod(g_atlas, r, g, b);

    int len = (int)strlen(text);
    for (int i = 0; i < len; i++) {
        int c = (unsigned char)text[i];
        if (c < FIRST_CHAR || c > LAST_CHAR) c = FIRST_CHAR;
        c -= FIRST_CHAR;

        int col = c % ATLAS_COLS;
        int row = c / ATLAS_COLS;

        SDL_Rect src = {
            col * CHAR_W,
            row * CHAR_H,
            CHAR_W,
            CHAR_H
        };
        SDL_Rect dst = {
            x + i * CHAR_W * scale,
            y,
            CHAR_W * scale,
            CHAR_H * scale
        };
        SDL_RenderCopy(renderer, g_atlas, &src, &dst);
    }
}

int font_string_width(const char *text, int scale)
{
    if (!text) return 0;
    return (int)strlen(text) * CHAR_W * scale;
}
